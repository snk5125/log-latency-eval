#!/usr/bin/env bash
# =============================================================================
# gen-ansible-vars.sh — Terraform → Ansible variable bridge.
#
# WHY THIS EXISTS
#   The Ansible roles are written against deploy-time infrastructure facts
#   (bucket names, NLB / PrivateLink endpoint DNS, SQS URLs) that only exist
#   after `terraform apply`. Rather than hand-editing role defaults, this
#   script renders a single generated group_vars file that the dynamic
#   inventory picks up automatically:
#
#       ansible/inventories/group_vars/all/generated_infra.yml   (GITIGNORED)
#
#   Run automatically by setup.sh (step 4b); safe to re-run any time the
#   Terraform outputs change. A committed .example shows the expected shape.
#
# IMPORTANT ROUTING DETAIL (PLAN §4.2/§4.4)
#   Agents live in the SENDER account and must reach Tier-1 through the
#   PrivateLink *interface endpoint* DNS (sender_*_endpoint_dns outputs) —
#   NOT the NLB DNS, which resolves only inside the logging VPC. Tier-1→Tier-2
#   traffic stays in the logging VPC, so Tier-2 vars use the NLB DNS directly.
#
# FAIL-LOUD CONTRACT (important — read before editing)
#   Every `tfo`/`tfo_epdns` lookup is assigned to a plain shell variable FIRST,
#   and the heredoc below is emitted ONLY from those already-resolved
#   variables — never from a command substitution embedded directly inside
#   the heredoc. This matters because a command substitution's `exit 1`
#   (inside tfo/tfo_epdns's `||` error branch) only terminates the SUBSHELL
#   that substitution runs in; if that substitution sat directly inside a
#   `cat > file <<EOF ... EOF` heredoc, the enclosing `cat` would still exit 0
#   and silently write an empty string for that value instead of aborting.
#   A plain assignment (`var="$(tfo ...)"`), by contrast, propagates the
#   subshell's failure to the assignment's own exit status, which DOES trigger
#   `set -e` and stops the script before anything is written. Keep this
#   assign-then-heredoc order for any new output var added here.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
TF_DIR="$REPO_ROOT/terraform"
OUT_DIR="$REPO_ROOT/ansible/inventories/group_vars/all"
OUT_FILE="$OUT_DIR/generated_infra.yml"

# Same env-overridable knobs as setup.sh / preflight.sh (PLAN §4.1).
LLT_SENDER_PROFILE="${LLT_SENDER_PROFILE:-llt-sender}"
LLT_LOGGING_PROFILE="${LLT_LOGGING_PROFILE:-llt-logging}"
AWS_REGION="${AWS_REGION:-us-east-2}"

command -v jq >/dev/null 2>&1 || { echo "ERROR: jq is required." >&2; exit 1; }

# Pull every root-module output once as JSON; fail loudly if state is absent.
TF_JSON="$(terraform -chdir="$TF_DIR" output -json)"
[ "$TF_JSON" != "{}" ] || { echo "ERROR: no terraform outputs — run terraform apply first." >&2; exit 1; }

# Helper: extract one output value or abort (missing output = drifted contract).
tfo() { echo "$TF_JSON" | jq -er --arg k "$1" '.[$k].value' \
  || { echo "ERROR: terraform output '$1' not found." >&2; exit 1; }; }

# Helper: interface-endpoint outputs are aws_vpc_endpoint.dns_entry lists of
# {dns_name, hosted_zone_id}; agents need the first (regional) DNS name.
tfo_epdns() { echo "$TF_JSON" | jq -er --arg k "$1" '.[$k].value[0].dns_name' \
  || { echo "ERROR: terraform output '$1' missing or not a dns_entry list." >&2; exit 1; }; }

mkdir -p "$OUT_DIR"

# --- Resolve every Terraform output into a shell variable FIRST --------------
# (fail-loud contract — see module docstring). If ANY of these lookups fails,
# `tfo`/`tfo_epdns`'s own error branch prints a clear message AND the failing
# assignment's non-zero status trips `set -e` right here, before OUT_FILE is
# touched at all — so a partially-resolved infra never gets written as a
# quietly-empty value.
llt_artifacts_bucket="$(tfo artifacts_bucket)"

vector_agg_t1_nlb="$(tfo_epdns sender_vector_endpoint_dns)"
vector_agg_t2_nlb="$(tfo vector_t2_nlb_dns)"
vector_landing_bucket="$(tfo landing_vagg_bucket)"
vector_final_bucket="$(tfo final_bucket)"
vector_landing_sqs_url="$(tfo landing_vagg_queue_url)"

cribl_edge_agg_t1_nlb="$(tfo_epdns sender_cribl_endpoint_dns)"
cribl_edge_landing_bucket="$(tfo landing_cs_bucket)"
cribl_agg_t2_nlb="$(tfo cribl_t2_nlb_dns)"
cribl_final_bucket="$(tfo final_bucket)"
cribl_landing_sqs_url="$(tfo landing_cs_queue_url)"

# --- Render the group_vars file from the already-resolved variables ---------
# Every var below is consumed by the Ansible layer:
#   llt_*                    → connection plumbing (site.yml, playbooks)
#   vector_* / cribl_*       → role defaults overridden with real infra values
# Output keys are unchanged from prior versions of this script — Ansible
# consumers read these exact names.
cat > "$OUT_FILE" <<EOF
---
# GENERATED by scripts/gen-ansible-vars.sh — DO NOT EDIT, DO NOT COMMIT.
# Regenerate after any terraform apply.

# --- Global plumbing (PLAN §4.1, §7) -----------------------------------------
llt_aws_region: "$AWS_REGION"
# NOTE: llt_ssm_profile is intentionally NOT set here. It is composed PER HOST
# in the aws_ec2 inventories (sender -> sender profile, logging -> logging
# profile). A group_vars/all default would override that per-host value (group
# vars win over inventory compose), making every host use one account's profile
# and breaking cross-account SSM (logging hosts -> TargetNotConnected).
llt_logging_profile: "$LLT_LOGGING_PROFILE"
llt_artifacts_bucket: "$llt_artifacts_bucket"

# --- Vector stack (agents reach T1 via PrivateLink endpoint DNS) -------------
vector_agg_t1_nlb: "$vector_agg_t1_nlb"
vector_agg_t2_nlb: "$vector_agg_t2_nlb"
vector_landing_bucket: "$vector_landing_bucket"
vector_final_bucket: "$vector_final_bucket"
vector_landing_sqs_url: "$vector_landing_sqs_url"

# --- Cribl stack --------------------------------------------------------------
cribl_edge_agg_t1_nlb: "$cribl_edge_agg_t1_nlb"
cribl_edge_landing_bucket: "$cribl_edge_landing_bucket"
cribl_agg_t2_nlb: "$cribl_agg_t2_nlb"
cribl_final_bucket: "$cribl_final_bucket"
cribl_landing_sqs_url: "$cribl_landing_sqs_url"
EOF

echo "Wrote $OUT_FILE"
